package dev.kof.compiler.nat.mcu;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/** kof.esp8266 — THE IMAGE LAW (its own class: the 500 gate split, the
 *  {@link NativeEsp8266Runtime}/{@link NativeEsp8266MemoryReport} precedent).
 *
 *  <p>Two halves, both MEASURED on the real ESP8266EX (15/11, the gate-5
 *  hardware bring-up):
 *  <ul>
 *   <li>the LINKER SCRIPT: esp8266 ships NONE (measured, gate 0), so the
 *       emitter writes its own. Two laws live in it — the ENTRY law
 *       ({@code ENTRY(_start)}: the default ELF entry landed on the crt0
 *       literal pool, and the CPU executed a literal word as an instruction →
 *       Fatal exception 0 at {@code epc1=0x40200010}, measured in a crash
 *       loop) and the IRAM law (the whole .text in the RAM window
 *       0x40100000: the V1 ROM loader loads ONLY the image's RAM segments and
 *       does NOT map the flash into 0x40200000 — code in the flash-mapped
 *       region faults at its first word, measured);</li>
 *   <li>the FIRMWARE IMAGE: esptool turns the ELF into the real flash images
 *       (the boot section at 0x0, the app at 0x10000). esptool 5.x: the
 *       {@code --chip} comes BEFORE the subcommand.</li>
 *  </ul>
 */
final class NativeEsp8266Image {

    private NativeEsp8266Image() {}

    /** The linker script: esp8266 ships NONE (measured, gate 0) — the emitter
     *  writes its own with the REAL memory map (the `NativeMcuRiscv32` pattern).
     *  THE GATE-5 HARDWARE LAW (measured on the ESP8266EX, 15/11): the V1 ROM
     *  loader loads ONLY the image's RAM segments and jumps to the image entry —
     *  it does NOT map the flash into 0x40200000 (no cache setup). Code that
     *  lives in the flash-mapped region faults with Fatal exception (0) at its
     *  first instruction. The gate-5 subset's code is tiny (1 KB measured), so
     *  the WHOLE app runs from IRAM at 0x40100000: the .text/.literal sections
     *  are LOADABLE RAM segments there, the ROM copies them out of the image and
     *  executes them directly. The flash-mapped irom region stays for a future
     *  software-bootloader face (that loader would enable the flash cache). */
    static String linkerScript() {
        return """
                /* kof.esp8266 — generated by NativeEsp8266 (gate 5 hardware) */
                MEMORY
                {
                  iram0_0_seg : org = 0x40100000, len = 0x8000
                  irom0_0_seg : org = 0x40200010, len = 0xf0000
                  dram0_0_seg : org = 0x3FFE8000, len = 0x14000
                }
                PHDRS { dram0_0_phdr PT_LOAD; iram0_0_phdr PT_LOAD; }
                ENTRY(_start)
                SECTIONS
                {
                  .data : { *(.data) *(.rodata) *(.rodata.*) } > dram0_0_seg :dram0_0_phdr
                  .text : { *(.literal) *(.text) *(.text.*) } > iram0_0_seg :iram0_0_phdr
                  .bss  : { *(.bss) *(.bss.*) *(COMMON) } > dram0_0_seg :dram0_0_phdr
                }
                """;
    }


    /** The FIRMWARE IMAGE (the gate-1 exit artifact): esptool produces the real
     *  flash images. The tool is probed (`KOF_ESPTOOL` or the PATH python);
     *  absent -> a NAMED skip (the ELF remains the deliverable) — never a
     *  silent nothing. esptool 5.x: `--chip` comes BEFORE the subcommand; the
     *  split images land at <elf>.img<offset>.bin (0x00000 = the boot section,
     *  0x00010 = the app — the REAL ESP8266 flash layout, measured). */
    static void firmwareImage(Path elf) {
        String esp = System.getenv().getOrDefault("KOF_ESPTOOL", "python3 -m esptool");
        String[] cmd = esp.split("\\s+");
        String[] full = new String[cmd.length + 6];
        System.arraycopy(cmd, 0, full, 0, cmd.length);
        full[cmd.length] = "--chip";
        full[cmd.length + 1] = "esp8266";
        full[cmd.length + 2] = "elf2image";
        full[cmd.length + 3] = "--output";
        full[cmd.length + 4] = elf + ".img";
        full[cmd.length + 5] = elf.toString();
        try {
            NativeEsp8266.run(full, "esp8266-esptool");
            System.err.println("NativeEsp8266: firmware image " + elf + ".img*.bin"
                    + " (the boot section + the app section)");
        } catch (IOException | IllegalStateException e) {
            System.err.println("NativeEsp8266: esptool absent - the firmware image"
                    + " step is SKIPPED (named; the ELF is the deliverable): " + e.getMessage());
        }
    }

}
