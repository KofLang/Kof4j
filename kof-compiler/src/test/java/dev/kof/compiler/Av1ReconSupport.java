/**
 * Independent data source for AVIF slice 3i (the AV1 reconstruction,
 * {@code libs/image/Av1Recon.kf}). The Kof module is a direct transcription of
 * AV1 Bitstream &amp; Decoding Process Specification §7.11.4 (reconstruct
 * process), steps 2 and 3; this class pins its output against the reference
 * libaom implementation, built on the dev host: a copy of libaom's
 * {@code inv_txfm2d_add_c} ({@code av1/common/av1_inv_txfm2d.c}) with the
 * FLIPADST index flips ENABLED and the residual added to a prediction buffer
 * with {@code Clip1}. The dump is gzip-compressed and base64-encoded as the
 * test resource {@code av1_recon_golden.txt.b64}.
 *
 * <p>Only transform type/size pairs that libaom maps to a real 1D kernel are
 * exercised (a 64-wide axis only admits DCT, etc.), over bit depths 8/10/12,
 * which is exactly the set the spec's branch tables admit. The prediction is a
 * deterministic ramp so the {@code Clip1} boundary is crossed.
 */
