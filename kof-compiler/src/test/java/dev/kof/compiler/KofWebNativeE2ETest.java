package dev.kof.compiler;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.*;

/**
 * WEB002 — kof.web servidor para o target Nativo.
 *
 * T1: accept loop + resposta 200/hello (commit 89ac0d9)
 * T2: parse METHOD+PATH + match literal → 200/404 (commit 6ad63f8)
 * T3 (em andamento): dispatch do handler lambda via trampolim invoke().
 */
class KofWebNativeE2ETest extends ServerProcessSupport {

    private int serverPort = -1;


    private static final String SERVER_T1 = """
            main() {
                var app = web.app()
                app.get("/") {
                    return "hello"
                }
                app.listen(PORT)
            }
            """;

    private static final String SERVER_T2 = """
            main() {
                var app = web.app()
                app.get("/hello") {
                    return "ok-matched"
                }
                app.listen(PORT)
            }
            """;

    // ---------------- helpers ----------------

    private static int freePort() throws IOException {
        try (java.net.ServerSocket s = new java.net.ServerSocket(0)) {
            return s.getLocalPort();
        }
    }

    private Process startServer(Path tempDir, String source) throws Exception {
        int port = freePort();
        serverPort = port;
        Path src = tempDir.resolve("App.kf");
        Files.writeString(src, source.replace("PORT", String.valueOf(port)));
        CompilerDriver driver = new CompilerDriver();
        CompilationResult result = driver.compile(src, tempDir.resolve("classes"), Target.NATIVE);
        assertTrue(result.success(), "compile: " + result.diagnostics().getDiagnostics());
        Path binary = tempDir.resolve("classes/Default/Main");
        assertTrue(Files.exists(binary), "native binary should exist");
        ProcessBuilder pb = new ProcessBuilder(binary.toString());
        pb.redirectErrorStream(true);
        Process p = pb.start();
        TestServerFixture.awaitListening(p, port, 100, 50);
        return p;
    }

    private int portFromServer(String source) throws IOException {
        // Generated by test server — guaranteed valid integer
        @SuppressWarnings("NumberFormatException")
        int parsed = Integer.parseInt(source.split("app.listen\\(")[1].split("\\)")[0]);
        return parsed;
    }

    private String httpGet(int port, String path) throws IOException {
        try (Socket s = new Socket("127.0.0.1", port)) {
            s.getOutputStream().write(("GET " + path + " HTTP/1.1\r\nHost: x\r\nConnection: close\r\n\r\n")
                    .getBytes(StandardCharsets.UTF_8));
            s.getOutputStream().flush();
            return new String(s.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    // ---------------- testes ----------------

    /**
     * §1159 (20/11): o CONTEXTO da request corrente no nativo x86-64 —
     * {@code method()} e {@code path()} devolvem o método e o path da request
     * que casou a rota. Antes recusavam em compile-time (WEB001) e o ticket
     * listava "path params" como residual do nativo.
     */
    private static final String SERVER_CTX = """
            main() {
                var app = web.app()
                app.get("/ctx/7") {
                    return "m=" + method() + " p=" + path()
                }
                app.listen(PORT)
            }
            """;

    /**
     * §1159 (20/11): o STATUS da resposta no nativo x86-64 — `status(404,
     * "gone")` guarda o código (e devolve o body) e o escritor de resposta
     * emite "HTTP/1.1 404 Not Found" no fio. Antes recusava em compile-time
     * (WEB001).
     */
    private static final String SERVER_STATUS = """
            main() {
                var app = web.app()
                app.get("/gone") {
                    return status(404, "gone")
                }
                app.get("/created") {
                    return status(201, "made")
                }
                app.listen(PORT)
            }
            """;

    /**
     * §1159 (20/11): os PATH PARAMS no nativo — `app.get("/item/:id")` casa
     * e `param("id")` devolve o segmento do path da request. Antes o match
     * era string exata (o padrão `:id` nunca casava).
     */
    private static final String SERVER_PARAMS = """
            main() {
                var app = web.app()
                app.get("/item/:id") {
                    return "id=" + param("id")
                }
                app.get("/user/:name/pet/:pet") {
                    return param("name") + "/" + param("pet")
                }
                app.get("/plain") {
                    return "plain"
                }
                app.listen(PORT)
            }
            """;

    @Test
    void nativeServerCapturesPathParams(@TempDir Path tempDir) throws Exception {
        serverProcess = startServer(tempDir, SERVER_PARAMS);
        String one = httpGet(serverPort, "/item/42");
        assertTrue(one.contains("200"), "status: " + one);
        assertTrue(one.endsWith("id=42"), "the :id segment must be captured: " + one);
        String two = httpGet(serverPort, "/user/mel/pet/rex");
        assertTrue(two.endsWith("mel/rex"), "two params in one route: " + two);
        String plain = httpGet(serverPort, "/plain");
        assertTrue(plain.endsWith("plain"), "the literal route still matches: " + plain);
        String miss = httpGet(serverPort, "/nope");
        assertTrue(miss.contains("404"), "a non-matching path still 404s: " + miss);
    }

    @Test
    void nativeServerEmitsTheStatusTheHandlerSet(@TempDir Path tempDir) throws Exception {
        serverProcess = startServer(tempDir, SERVER_STATUS);
        String notFound = httpGet(serverPort, "/gone");
        assertTrue(notFound.contains("404"), "the status line must carry the code: " + notFound);
        assertTrue(notFound.contains("Not Found"), "the status text must be the standard one: " + notFound);
        assertTrue(notFound.endsWith("gone"), "the body must be what status() returned: " + notFound);
        String created = httpGet(serverPort, "/created");
        assertTrue(created.contains("201"), "the status line must carry the code: " + created);
        assertTrue(created.contains("Created"), "the status text must be the standard one: " + created);
        assertTrue(created.endsWith("made"), "the body must be what status() returned: " + created);
    }

    @Test
    void nativeServerExposesTheRequestMethodAndPath(@TempDir Path tempDir) throws Exception {
        serverProcess = startServer(tempDir, SERVER_CTX);
        String resp = httpGet(serverPort, "/ctx/7");
        assertTrue(resp.contains("200"), "status: " + resp);
        assertTrue(resp.endsWith("m=GET p=/ctx/7"),
                "the request context must carry the method and the path: " + resp);
    }

    @Test
    void nativeServerAcceptsAndResponds200(@TempDir Path tempDir) throws Exception {
        serverProcess = startServer(tempDir, SERVER_T1);
        String resp = httpGet(serverPort, "/");
        assertTrue(resp.startsWith("HTTP/1.1 200") || resp.contains(" 200 "),
                "servidor nativo tem de responder 200 ao GET /: " + resp);
    }

    @Test
    void nativeServerMatchesLiteralRoute(@TempDir Path tempDir) throws Exception {
        int port = freePort();
        Path src = tempDir.resolve("App.kf");
        Files.writeString(src, SERVER_T2.replace("PORT", String.valueOf(port)));
        CompilerDriver driver = new CompilerDriver();
        CompilationResult result = driver.compile(src, tempDir.resolve("classes"), Target.NATIVE);
        assertTrue(result.success(), "compile: " + result.diagnostics().getDiagnostics());
        ProcessBuilder pb = new ProcessBuilder(tempDir.resolve("classes/Default/Main").toString());
        pb.redirectErrorStream(true);
        serverProcess = pb.start();
        TestServerFixture.awaitListening(serverProcess, port, 100, 50);
        String match = httpGet(port, "/hello");
        assertTrue(match.contains("200"), "match: " + match);
        assertTrue(match.endsWith("ok-matched"), "match body: " + match);
        String miss = httpGet(port, "/estanaoexiste");
        assertTrue(miss.contains("404"), "miss: " + miss);
        assertTrue(miss.endsWith("Not Found"), "miss body: " + miss);
    }

    @Test
    void nativeServerDispatchesLambdaHandler(@TempDir Path tempDir) throws Exception {
        int port = freePort();
        Path src = tempDir.resolve("App.kf");
        Files.writeString(src, SERVER_T2.replace("PORT", String.valueOf(port)));
        CompilerDriver driver = new CompilerDriver();
        CompilationResult result = driver.compile(src, tempDir.resolve("classes"), Target.NATIVE);
        assertTrue(result.success(), "compile: " + result.diagnostics().getDiagnostics());
        ProcessBuilder pb = new ProcessBuilder(tempDir.resolve("classes/Default/Main").toString());
        pb.redirectErrorStream(true);
        serverProcess = pb.start();
        TestServerFixture.awaitListening(serverProcess, port, 100, 50);
        String r = httpGet(port, "/hello");
        assertTrue(r.contains("HTTP/1.1 200"), "status: " + r);
        assertTrue(r.endsWith("ok-matched"), "body should come from handler, got: " + r);
    }

    private static final String SERVER_T4 = """
            main() {
                var app = web.app()
                app.post("/echo") {
                    return "got: " + body()
                }
                app.listen(PORT)
            }
            """;

    @Test
    void nativeServerReadsBodyContext(@TempDir Path tempDir) throws Exception {
        int port = freePort();
        Path src = tempDir.resolve("App.kf");
        Files.writeString(src, SERVER_T4.replace("PORT", String.valueOf(port)));
        CompilerDriver driver = new CompilerDriver();
        CompilationResult result = driver.compile(src, tempDir.resolve("classes"), Target.NATIVE);
        assertTrue(result.success(), "compile: " + result.diagnostics().getDiagnostics());
        ProcessBuilder pb = new ProcessBuilder(tempDir.resolve("classes/Default/Main").toString());
        pb.redirectErrorStream(true);
        serverProcess = pb.start();
        TestServerFixture.awaitListening(serverProcess, port, 100, 50);
        try (Socket s = new Socket("127.0.0.1", port)) {
            s.getOutputStream().write("POST /echo HTTP/1.1\r\nHost: x\r\nContent-Length: 5\r\n\r\nhello"
                    .getBytes(StandardCharsets.UTF_8));
            s.getOutputStream().flush();
            String r = new String(s.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            assertTrue(r.contains("200"), "status: " + r);
            assertTrue(r.endsWith("got: hello"), "body() should echo, got: " + r);
        }
    }
}
